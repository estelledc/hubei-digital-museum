    o=b.lathe('四爱梅瓶_丰肩短颈_圈足_中空瓶口',profile,glaze,192)
    # Four observed story panels. Their circumferential registration is approximate.
    # Coordinate measurements refer to 1280x1920 previews of the unmodified originals.
    photos=[('front',630,162,1789,406),('wang',606,270,1788,414),('tao',580,237,1738,402),('zhou',638,392,1574,322)]
    # Bake the four calibrated projections into one cylindrical UV atlas. Smooth
    # angular weights avoid hard material boundaries; this is photographic
    # registration, not a recovered seamless scan texture.
    w,h=4096,2048
    angles=np.arange(w,dtype=np.float32)/w*TAU
    zs=np.arange(h,dtype=np.float32)/(h-1)*.387
    radius=np.interp(zs,[p[1] for p in knots],[p[0] for p in knots])
    atlas=np.zeros((h,w,3),np.float32);total=np.zeros((1,w,1),np.float32)
    reference_white=None;front_foot=None
    for q,(slug,cx,top,bottom,half) in enumerate(photos):
        im=bpy.data.images.load(str(ROOT/'research'/('vase-'+slug+'-hd.jpg')),check_existing=True)
        f=min(1,4096/max(im.size));im.scale(round(im.size[0]*f),round(im.size[1]*f))
        iw,ih=im.size;buf=np.empty(iw*ih*4,np.float32);im.pixels.foreach_get(buf)
        pixels=buf.reshape(ih,iw,4)[:,:,:3]
        delta=(angles-q*math.pi/2+math.pi)%TAU-math.pi
        sx=radius[:,None]*np.sin(delta)[None,:]
        px=np.clip((cx+sx/.1*half)/1280*(iw-1),0,iw-1)
        py=np.clip((1-(bottom-zs/.387*(bottom-top))/1920)*(ih-1),0,ih-1)
        x0=px.astype(int);x1=np.minimum(x0+1,iw-1);y0=py.astype(int);y1=np.minimum(y0+1,ih-1)
        tx=(px-x0)[:,:,None];ty=(py-y0)[:,None,None]
        colour=(pixels[y0[:,None],x0]*(1-tx)+pixels[y0[:,None],x1]*tx)*(1-ty)+(pixels[y1[:,None],x0]*(1-tx)+pixels[y1[:,None],x1]*tx)*ty
        # Calibrate photographed illumination from bright glaze within each view.
        # A single row gain preserves blue hues and actual brushwork.
        center_band=np.abs(delta)<.4
        luminance=colour[:,center_band,:]@np.array([.2126,.7152,.0722])
        white=np.quantile(luminance,.88,axis=1)
        white=np.convolve(np.pad(white,(20,20),mode='edge'),np.ones(41)/41,mode='valid')
        if q==0:reference_white=white;front_foot=colour.copy()
        else:colour*=np.clip(reference_white/np.maximum(white,.01),.55,2.5)[:,None,None]
        # Avoid supports visible at the outside edges of the older photographs.
        if q:
            foot_mix=np.clip((.10-zs)/.04,0,1)[:,None,None]
            colour=colour*(1-foot_mix)+np.roll(front_foot,q*w//4,axis=1)*foot_mix
        weight=np.clip((math.pi/4+.13-np.abs(delta))/.26,0,1)
        weight=weight*weight*(3-2*weight)
        atlas+=colour*weight[None,:,None];total+=weight[None,:,None]
    atlas=np.clip(atlas/np.maximum(total,.001),0,1)
    packed=bpy.data.images.new('四爱四面照片_曝光校准与接缝混合',width=w,height=h,alpha=False)
    packed.colorspace_settings.name='sRGB'
    rgba=np.ones((h,w,4),np.float32);rgba[:,:,:3]=atlas
    packed.pixels.foreach_set(rgba.ravel());packed.pack()
    m=mat('四爱梅瓶_四面实拍环向贴图','#ffffff',0,.34)
    tex=m.node_tree.nodes.new('ShaderNodeTexImage');tex.image=packed
    m.node_tree.links.new(tex.outputs['Color'],m.node_tree.nodes['Principled BSDF'].inputs['Base Color'])
    m.node_tree.nodes['Principled BSDF'].inputs['Coat Weight'].default_value=.12
    m['texture_method']='Four photographs reprojected; row exposure calibrated; angular seams blended. CC BY-SA 4.0; see fidelity-sources.json.'
    o.data.materials.append(m)
    uv=o.data.uv_layers.active
    for face in o.data.polygons:
        if face.index//192>=len(profile)-5:continue
        face.material_index=1
        center=(math.atan2(face.center.y,face.center.x)+math.pi/2)%TAU
        for li in face.loop_indices:
            v=o.data.vertices[o.data.loops[li].vertex_index].co
            angle=(math.atan2(v.y,v.x)+math.pi/2)%TAU
            if angle-center>math.pi:angle-=TAU
            if center-angle>math.pi:angle+=TAU
            uv.data[li].uv=(angle/TAU,v.z/.387)

