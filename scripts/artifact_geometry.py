def linear(c):
    v=np.array([int(c[i:i+2],16)/255 for i in (1,3,5)])
    return np.where(v<=.04045,v/12.92,((v+.055)/1.055)**2.4)

def mat(name,color,metal=0,rough=.5):
    m=bpy.data.materials.new(name);m.use_nodes=True
    p=m.node_tree.nodes.get('Principled BSDF');p.inputs['Base Color'].default_value=(*linear(color),1)
    p.inputs['Metallic'].default_value=metal;p.inputs['Roughness'].default_value=rough
    m.diffuse_color=(*linear(color),1)
    return m

def image_material(name,file,metal=0,rough=.5,maxsize=4096):
    m=mat(name,'#ffffff',metal,rough)
    im=bpy.data.images.load(str(ROOT/'research'/file),check_existing=True)
    if max(im.size)>maxsize:
        f=maxsize/max(im.size);im.scale(round(im.size[0]*f),round(im.size[1]*f))
    im.pack();im.colorspace_settings.name='sRGB'
    tex=m.node_tree.nodes.new('ShaderNodeTexImage');tex.image=im;tex.extension='EXTEND'
    m.node_tree.links.new(tex.outputs['Color'],m.node_tree.nodes['Principled BSDF'].inputs['Base Color'])
    m['texture_method']='registered photograph projection; lighting and perspective remain in the photo'
    return m

def aged(name,base,metal=.4,rough=.65):
    """A restrained, explicitly procedural surface study, with exported PBR maps."""
    m=mat(name,base,metal,rough);n=512
    rng=np.random.default_rng(39);v=np.zeros((n,n),dtype=np.float32)
    # Periodic interpolated random fields give granular patina without artificial stripes.
    yy,xx=np.mgrid[0:n,0:n]/n
    for grid,amp in [(7,.13),(23,.08),(67,.055),(191,.025)]:
        values=rng.normal(0,1,(grid,grid))
        x=xx*grid;y=yy*grid;ix=x.astype(int);iy=y.astype(int)
        tx=x-ix;ty=y-iy;tx=tx*tx*(3-2*tx);ty=ty*ty*(3-2*ty)
        v+=amp*((1-tx)*(1-ty)*values[iy%grid,ix%grid]+tx*(1-ty)*values[iy%grid,(ix+1)%grid]+(1-tx)*ty*values[(iy+1)%grid,ix%grid]+tx*ty*values[(iy+1)%grid,(ix+1)%grid])
    v+=rng.normal(0,.026,(n,n))
    colour=np.clip(linear(base)[None,None,:]*(1+v[:,:,None]*1.4),.001,1)
    def generated(label,values,space):
        im=bpy.data.images.new(name+'_'+label,width=n,height=n,alpha=False)
        im.colorspace_settings.name=space
        data=np.ones((n,n,4),dtype=np.float32);data[:,:,:3]=values
        im.pixels.foreach_set(data.ravel());im.pack()
        t=m.node_tree.nodes.new('ShaderNodeTexImage');t.image=im;return t
    # Generated byte images store encoded values; scene-linear values here would
    # be decoded a second time by the sRGB image texture and darken the material.
    encoded=np.where(colour<=.0031308,colour*12.92,1.055*colour**(1/2.4)-.055)
    albedo=generated('Albedo',encoded,'sRGB')
    r=generated('Roughness',np.repeat(np.clip(rough+v*.35,.2,.95)[:,:,None],3,2),'Non-Color')
    dx=(np.roll(v,1,1)-np.roll(v,-1,1))*.8;dy=(np.roll(v,1,0)-np.roll(v,-1,0))*.8
    normals=np.stack([dx,dy,np.ones_like(v)],axis=2);normals/=np.linalg.norm(normals,axis=2,keepdims=True)
    t=generated('Normal',normals*.5+.5,'Non-Color')
    normal=m.node_tree.nodes.new('ShaderNodeNormalMap');normal.inputs['Strength'].default_value=.35
    ls=m.node_tree.links;p=m.node_tree.nodes['Principled BSDF']
    ls.new(albedo.outputs['Color'],p.inputs['Base Color']);ls.new(r.outputs['Color'],p.inputs['Roughness'])
    ls.new(t.outputs['Color'],normal.inputs['Color']);ls.new(normal.outputs[0],p.inputs['Normal'])
    m['surface_accuracy']='procedural micro-surface, not recovered corrosion or scan data'
    m['albedo_encoding']='srgb-byte-v1'
    return m

class Builder:
    def __init__(self,c):self.c=c;self.objects=[]
    def add(self,o,name,m):
        o.name=name
        for c in list(o.users_collection):c.objects.unlink(o)
        self.c.objects.link(o)
        if m:o.data.materials.append(m)
        self.objects.append(o)
        return o
    def mesh(self,name,v,f,m,smooth=True):
        d=bpy.data.meshes.new(name);d.from_pydata(v,[],f);d.update()
        o=bpy.data.objects.new(name,d);self.add(o,name,m)
        for p in d.polygons:p.use_smooth=smooth
        self.uv(o,lambda v:(v.x*12,v.z*12+v.y*7))
        return o
    def uv(self,o,fn):
        layer=o.data.uv_layers.active or o.data.uv_layers.new(name='ArtifactUV')
        layer.name='ArtifactUV'
        for p in o.data.polygons:
            for li in p.loop_indices:layer.data[li].uv=fn(o.data.vertices[o.data.loops[li].vertex_index].co)
    def ellipsoid(self,name,loc,scale,m,segments=32,rings=16):
        bpy.ops.mesh.primitive_uv_sphere_add(segments=segments,ring_count=rings,location=loc)
        o=self.add(bpy.context.object,name,m);o.scale=scale
        bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
        for p in o.data.polygons:p.use_smooth=True
        return o
    def box(self,name,loc,size,m,bevel):
        bpy.ops.mesh.primitive_cube_add(size=1,location=loc);o=self.add(bpy.context.object,name,m);o.dimensions=size
        bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
        mod=o.modifiers.new('Rounded cut edges','BEVEL');mod.width=bevel;mod.segments=3
        return o
    def tube(self,name,pts,r,m,sides=10):
        points=[Vector(p) for p in pts];verts=[];faces=[]
        for i,p in enumerate(points):
            tangent=(points[min(i+1,len(points)-1)]-points[max(i-1,0)]).normalized()
            seed=Vector((0,1,0)) if abs(tangent.y)<.9 else Vector((1,0,0))
            u=tangent.cross(seed).normalized();w=tangent.cross(u).normalized()
            rr=r[i] if isinstance(r,list) else r
            rx,ry=rr if isinstance(rr,tuple) else (rr,rr)
            for k in range(sides):verts.append(tuple(p+u*math.cos(k*TAU/sides)*rx+w*math.sin(k*TAU/sides)*ry))
        for j in range(len(points)-1):
            for k in range(sides):faces.append((j*sides+k,j*sides+(k+1)%sides,(j+1)*sides+(k+1)%sides,(j+1)*sides+k))
        faces+=[tuple(reversed(range(sides))),tuple((len(points)-1)*sides+k for k in range(sides))]
        return self.mesh(name,verts,faces,m)
    def lathe(self,name,profile,m,segments=128):
        vs=[(r*math.cos(i*TAU/segments),r*math.sin(i*TAU/segments),z) for r,z in profile for i in range(segments)]
        fs=[(j*segments+i,j*segments+(i+1)%segments,(j+1)*segments+(i+1)%segments,(j+1)*segments+i) for j in range(len(profile)-1) for i in range(segments)]
        o=self.mesh(name,vs,fs,m)
        self.uv(o,lambda v:(math.atan2(v.y,v.x)/TAU+.5,v.z*5))
        return o
    def polygon(self,name,xz,depth,m,bevel=.003,y=0):
        # Explicit silhouette with rounded solid sidewalls, never a billboard.
        if sum(xz[i][0]*xz[(i+1)%len(xz)][1]-xz[(i+1)%len(xz)][0]*xz[i][1] for i in range(len(xz)))<0:xz=list(reversed(xz))
        v=[(x,y-d/2,z) for d in [depth,-depth] for x,z in xz];n=len(xz)
        fs=[tuple(range(n)),tuple(reversed(range(n,n*2)))]+[(i,(i+1)%n,(i+1)%n+n,i+n) for i in range(n)]
        o=self.mesh(name,v,fs,m,False)
        mod=o.modifiers.new('Carved silhouette edge','BEVEL');mod.width=bevel;mod.segments=4
        mod=o.modifiers.new('Carved face normals','WEIGHTED_NORMAL');mod.keep_sharp=True
        return o

def interpolate(points,steps=6):
    # Catmull-Rom sampling for continuous carved necks, tails and ornamental scrolls.
    ps=[np.array(p,float) for p in points];out=[]
    for i in range(len(ps)-1):
        p0,p1,p2,p3=ps[max(0,i-1)],ps[i],ps[i+1],ps[min(len(ps)-1,i+2)]
        for j in range(steps):
            t=j/steps
            out.append(tuple(.5*((2*p1)+(-p0+p2)*t+(2*p0-5*p1+4*p2-p3)*t*t+(-p0+3*p1-3*p2+p3)*t*t*t)))
    return out+[tuple(ps[-1])]

