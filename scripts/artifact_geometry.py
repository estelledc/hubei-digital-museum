def vase(b):
    glaze=mat('梅瓶内壁青白釉','#d6d2bc',0,.25)
    # Smooth profile registered to the front photo; height/neck/foot from museum data.
    knots=[(.065,0),(.065,.005),(.063,.013),(.063,.030),(.064,.06),(.069,.10),(.079,.16),(.092,.23),(.099,.28),(.100,.30),(.096,.32),(.087,.337),(.072,.349),(.050,.358),(.029,.362),(.027,.367),(.027,.376),(.032,.383),(.032,.387)]
